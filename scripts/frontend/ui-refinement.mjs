import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { chromium } from 'playwright';
import { startPreview } from './server.mjs';

const preview = await startPreview();
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 950 }, reducedMotion: 'reduce' });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
await page.addInitScript(() => localStorage.setItem('benchpoll-welcome-seen-v1', '1'));
await mkdir('artifacts/ui-refinement', { recursive: true });
try {
    await page.goto(preview.url);
    await page.locator('#model-comparison-toggle:not([disabled])').waitFor();
    assert.equal(await page.locator('#configured-search-wrap').isVisible(), false);
    await page.locator('#model-comparison-toggle').click();
    const applyResponse = page.waitForResponse(response => response.url().endsWith('/api/get_weighted_workspace'));
    await page.getByRole('button', { name: 'Add Thinking filter' }).click(); await applyResponse;
    assert.equal(await page.locator('#model-comparison-toggle').evaluate(node => node.classList.contains('has-active-filters')), true);
    await page.screenshot({ path: 'artifacts/ui-refinement/desktop.png', fullPage: true });
    const resetResponse = page.waitForResponse(response => response.url().endsWith('/api/get_weighted_workspace'));
    await page.getByRole('button', { name: 'Reset', exact: true }).click(); await resetResponse;
    assert.equal(await page.locator('#model-comparison-toggle').evaluate(node => node.classList.contains('has-active-filters')), false);
    await page.locator('#model-comparison-close').click();
    const width = await page.locator('#pie-card').evaluate(node => node.getBoundingClientRect().width);
    await page.locator('#pie-card').evaluate(node => { node.style.minHeight = '1800px'; });
    const scrollbar = page.getByRole('scrollbar', { name: 'Scroll weights' });
    await scrollbar.waitFor();
    assert.equal(await page.locator('#pie-card').evaluate(node => node.getBoundingClientRect().width), width);
    assert.equal(await page.locator('#pie-home-slot').evaluate(node => node.clientWidth === node.offsetWidth), true);
    await scrollbar.focus(); await scrollbar.press('End');
    assert.ok(await page.locator('#pie-home-slot').evaluate(node => node.scrollTop) > 0);
    await scrollbar.press('Home');
    assert.equal(await page.locator('#pie-home-slot').evaluate(node => node.scrollTop), 0);
    const thumb = await scrollbar.locator('span').boundingBox();
    await page.mouse.move(thumb.x + thumb.width / 2, thumb.y + 5);
    await page.mouse.down(); await page.mouse.move(thumb.x + thumb.width / 2, thumb.y + 80); await page.mouse.up();
    assert.ok(await page.locator('#pie-home-slot').evaluate(node => node.scrollTop) > 0);
    await page.locator('#pie-card').evaluate(node => { node.style.minHeight = ''; });
    await page.locator('#discussion-entry').click();
    await page.locator('#discussion-feed[aria-busy="false"]').waitFor();
    await page.screenshot({ path: 'artifacts/ui-refinement/discussion.png', fullPage: true });
    await page.locator('#discussion-compose-toggle').click();
    await page.locator('#discussion-text').fill('A draft that survives closing the discussion.');
    await page.locator('#discussion-close').click();
    await page.locator('#discussion-entry').click();
    assert.equal(await page.locator('#discussion-text').inputValue(), 'A draft that survives closing the discussion.');
    await page.locator('#discussion-close').click();
    await page.locator('#beta-feedback-link').click();
    await page.locator('[data-bind="feedback"]').waitFor();
    assert.match(await page.locator('[data-bind="feedback"]').inputValue(), /BenchPoll Beta feedback[\s\S]*My suggestion:/);
    assert.equal(new URL(page.url()).pathname, '/contribute/feedback');
    assert.equal(new URL(page.url()).search, '');
    await page.reload();
    assert.match(await page.locator('[data-bind="feedback"]').inputValue(), /BenchPoll Beta feedback/);
    for (const width of [1024, 390, 320]) {
        await page.setViewportSize({ width, height: 844 });
        await page.goto(preview.url);
        await page.locator('#model-comparison-toggle:not([disabled])').waitFor({ state: 'attached' });
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
        if (width < 761) {
            assert.equal(await page.locator('#beta-feedback-link').isVisible(), false);
            assert.equal(await page.locator('#how-it-works-link').isVisible(), false);
            await page.locator('button[data-mobile-panel="models"]').click();
            await page.locator('#model-comparison-toggle').click();
            await page.getByRole('button', { name: 'Add Harness filter' }).click();
            await page.getByLabel('Harness value', { exact: true }).fill('Agent A');
            assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
            await page.screenshot({ path: `artifacts/ui-refinement/filters-${width}.png` });
            await page.locator('#model-comparison-close').click();
            await page.locator('#taxonomy-toggle').click();
            await page.locator('#navigation-search-toggle').click();
            await page.locator('#configured-search').fill('Language');
            await page.screenshot({ path: `artifacts/ui-refinement/navigation-${width}.png` });
            await page.locator('#taxonomy-close').click();
        }
        await page.locator('#discussion-entry').click();
        await page.locator('#discussion-feed[aria-busy="false"]').waitFor();
        await page.evaluate(() => document.fonts.ready);
        await page.waitForTimeout(350);
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), true);
        await page.screenshot({ path: `artifacts/ui-refinement/discussion-${width}.png` });
        await page.locator('#discussion-close').click();
    }
    await page.setViewportSize({ width: 1440, height: 950 });
    await page.goto(preview.url);
    await page.locator('#model-comparison-toggle:not([disabled])').click();
    await page.screenshot({ path: 'artifacts/ui-refinement/orange.png' });
    assert.deepEqual(errors, []);
    console.log('UI refinement passed: opt-in search, filters/reset, non-reserving scrollbar with keyboard/drag, discussion drafts, Beta prefill, 1440/1024/390/320 layouts.');
} finally { await browser.close(); await preview.close(); }
